"""Build the FSR 2.2 Vulkan permutations KarPur uses, without a runtime shader compiler.

The input is AMD's MIT-licensed GLSL in runtime/third_party/fsr2/shaders. Run with the
same glslc used for KarPur's own shaders; the generated header ships with the source.
"""

import hashlib
import os
import shutil
import struct
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHADERS = ROOT / 'runtime' / 'third_party' / 'fsr2' / 'shaders'
OUTPUT = ROOT / 'runtime' / 'fsr2_permutations.h'
PASSES = [
    'depth_clip', 'reconstruct_previous_depth', 'lock', 'accumulate',
    'accumulate', 'rcas', 'compute_luminance_pyramid', 'autogen_reactive',
    'tcr_autogen',
]
DEFINES = [
    ('FFX_FSR2_OPTION_REPROJECT_USE_LANCZOS_TYPE', 1),
    ('FFX_FSR2_OPTION_HDR_COLOR_INPUT', 2),
    ('FFX_FSR2_OPTION_LOW_RESOLUTION_MOTION_VECTORS', 4),
    ('FFX_FSR2_OPTION_JITTERED_MOTION_VECTORS', 8),
    ('FFX_FSR2_OPTION_INVERTED_DEPTH', 16),
    ('FFX_FSR2_OPTION_APPLY_SHARPENING', 32),
]


def main():
    compiler = shutil.which('glslc') or str(Path(os.environ.get('KARPUR_UCRT', r'C:\msys64\ucrt64')) / 'bin' / 'glslc.exe')
    if not Path(compiler).is_file():
        raise SystemExit('glslc not found; install the MSYS2 UCRT shaderc package to regenerate FSR 2 shaders')
    digest = hashlib.sha256()
    for source in sorted(SHADERS.iterdir()):
        if source.is_file():
            digest.update(source.name.encode())
            digest.update(source.read_bytes())
    lines = [f'// Generated by tools/build_fsr2_shaders.py from AMD FSR 2.2.1 (MIT); source sha256 {digest.hexdigest()}',
             '#pragma once', '#include <stdint.h>',
             'typedef struct { unsigned pass, options; const uint32_t *data; unsigned bytes; } Fsr2Compiled;', '']
    entries = []
    with tempfile.TemporaryDirectory() as tmp:
        blob = Path(tmp) / 'shader.spv'
        for i, name in enumerate(PASSES):
            part = [f'// AMD FSR 2.2.1 (MIT), pass {i}; generated by tools/build_fsr2_shaders.py', '#pragma once', '#include <stdint.h>']
            source = SHADERS / f'ffx_fsr2_{name}_pass.glsl'
            for depth in (0, 16):
                for lut in (0, 1):
                    options = 4 | depth | lut | (32 if i == 4 else 0)
                    cmd = [compiler, '-fshader-stage=compute', '--target-env=vulkan1.1', '-O0',
                           '-I', str(SHADERS), '-DFFX_GLSL=1', '-DFFX_GPU=1', '-DFFX_HALF=0']
                    cmd += [f'-D{key}={int(bool(options & bit))}' for key, bit in DEFINES]
                    cmd += ['-o', str(blob), str(source)]
                    subprocess.run(cmd, check=True, capture_output=True)
                    data = blob.read_bytes()
                    if len(data) % 4:
                        raise RuntimeError(f'{source.name}: SPIR-V size is not word aligned')
                    symbol = f'fsr2_spv_{i}_{options}'
                    words = struct.unpack(f'<{len(data) // 4}I', data)
                    part.append(f'static const uint32_t {symbol}[] = {{')
                    for start in range(0, len(words), 8):
                        part.append('    ' + ', '.join(f'0x{w:08x}' for w in words[start:start + 8]) + ',')
                    part.append('};')
                    entries.append(f'    {{{i}, {options}, {symbol}, sizeof {symbol}}},')
            fragment = OUTPUT.with_name(f'fsr2_permutations_{i}.h')
            fragment.write_text('\n'.join(part) + '\n', encoding='ascii', newline='\n')
            lines.append(f'#include "{fragment.name}"')
    lines.extend(['', 'static const Fsr2Compiled fsr2_compiled[] = {', *entries, '};', ''])
    OUTPUT.write_text('\n'.join(lines), encoding='ascii', newline='\n')
    print(f'{OUTPUT}: {len(entries)} permutations in {len(PASSES)} small headers')


if __name__ == '__main__':
    main()
